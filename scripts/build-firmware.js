#!/usr/bin/env node

/**
 * Đóng gói firmware/*.py thành constants/firmwareBundle.ts để app gửi qua BLE (OTA).
 *
 * Chạy: npm run firmware:bundle
 *
 * main.py và ota.py là file LÕI (launcher + OTA/rollback) nên không đưa vào gói,
 * muốn đổi 2 file này phải nạp lại qua USB.
 */

const fs = require("fs");
const path = require("path");
const crypto = require("crypto");
const { Buffer } = require("buffer");

const root = process.cwd();
const firmwareDir = path.join(root, "firmware");
const outFile = path.join(root, "constants", "firmwareBundle.ts");

const CORE_FILES = new Set(["main.py", "ota.py", "boot.py"]);
const INCLUDE_EXT = new Set([".py", ".json"]);

const CRC_TABLE = (() => {
  const table = new Uint32Array(256);
  for (let i = 0; i < 256; i++) {
    let c = i;
    for (let k = 0; k < 8; k++) c = c & 1 ? 0xedb88320 ^ (c >>> 1) : c >>> 1;
    table[i] = c >>> 0;
  }
  return table;
})();

const crc32 = (buf) => {
  let crc = 0xffffffff;
  for (const byte of buf) crc = CRC_TABLE[(crc ^ byte) & 0xff] ^ (crc >>> 8);
  return (crc ^ 0xffffffff) >>> 0;
};

const files = fs
  .readdirSync(firmwareDir)
  .filter(
    (name) =>
      INCLUDE_EXT.has(path.extname(name)) &&
      !CORE_FILES.has(name) &&
      fs.statSync(path.join(firmwareDir, name)).isFile(),
  )
  .sort()
  .map((name) => {
    // Chuẩn hoá CRLF -> LF để CRC không phụ thuộc cách git checkout trên Windows
    const content = Buffer.from(
      fs.readFileSync(path.join(firmwareDir, name), "utf8").replace(/\r\n/g, "\n"),
      "utf8",
    );
    return {
      name,
      size: content.length,
      crc: crc32(content),
      base64: content.toString("base64"),
    };
  });

const hash = crypto.createHash("sha1");
for (const f of files) hash.update(f.name).update(String(f.crc));
const version = hash.digest("hex").slice(0, 8);

const out = `// AUTO-GENERATED by scripts/build-firmware.js — đừng sửa tay.
// Sửa code trong firmware/ rồi chạy: npm run firmware:bundle

export type FirmwareFile = {
  name: string;
  size: number;
  crc: number;
  base64: string;
};

export const FIRMWARE_BUNDLE: {
  version: string;
  builtAt: string;
  files: FirmwareFile[];
} = ${JSON.stringify(
  { version, builtAt: new Date().toISOString(), files },
  null,
  2,
)};
`;

fs.writeFileSync(outFile, out);

const totalKb = (files.reduce((s, f) => s + f.size, 0) / 1024).toFixed(1);
console.log(
  `Firmware bundle ${version}: ${files.map((f) => f.name).join(", ")} (${totalKb} KB)`,
);
